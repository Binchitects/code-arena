    #[test]
    fn every_key_of_the_old_schema_is_declared() {
        assert_eq!(OLD.len(), 139);
        for key in OLD {
            assert!(find(key).is_some(), "{key} is not in the schema");
        }
        assert_eq!(ALL.len(), 150, "a row added here is added to the count; tests/settings_read.rs wants it read");
        for s in ALL {
            assert!(SECTIONS.contains(&s.section), "{} is under {:?}, which is no section", s.key, s.section);
            assert!(s.env.is_none(), "{} is not read from the environment", s.key);
        }
    }

    #[test]
    fn where_each_may_be_set_and_what_it_takes_are_the_old_ones() {
        let of = |key: &str| find(key).expect(key);
        // For a language too, a project's, the person's alone.
        assert_eq!(of("editor.tabSize").scope, Scope::Language);
        assert_eq!(of("files.insertFinalNewline").scope, Scope::Language);
        assert_eq!(of("files.autoSave").scope, Scope::Project);
        assert_eq!(of("editor.accessibilitySupport").scope, Scope::Project);
        for mine in [
            "terminal.integrated.allowChords",
            "terminal.integrated.sendKeybindingsToShell",
            "terminal.integrated.commandsToSkipShell",
            "codeArena.inlineCompletion.enabled",
        ] {
            assert_eq!(of(mine).scope, Scope::User, "{mine}");
        }
        // Code Arena's own defaults where they are not VS Code's.
        assert_eq!(of("editor.fontSize").default_value(), json!(13));
        assert_eq!(of("terminal.integrated.scrollback").default_value(), json!(10000));
        assert_eq!(of("codeArena.languageServers.json.enabled").default_value(), json!(false));
        // Numbers that are not whole, bounds, a line ending as a word, true or a word, a list of numbers.
        assert!(of("editor.fontSize").accepts(&json!(13.5)) && !of("editor.fontSize").accepts(&json!(5)));
        assert!(of("editor.tabSize").accepts(&json!(2)) && !of("editor.tabSize").accepts(&json!(2.5)));
        assert_eq!(of("editor.hover.delay").bounds(), (Some(0), None));
        assert!(of("editor.hover.delay").accepts(&json!(100_000)) && !of("editor.hover.delay").accepts(&json!(-1)));
        assert!(of("files.eol").accepts(&json!("\r\n")) && !of("files.eol").accepts(&json!("crlf")));
        let repositories = of("git.autoRepositoryDetection");
        assert!(repositories.accepts(&json!(false)) && repositories.accepts(&json!("openEditors")));
        assert!(!repositories.accepts(&json!("all")));
        assert!(of("editor.rulers").accepts(&json!([80, 120])) && !of("editor.rulers").accepts(&json!(["80"])));
        // An open list of names (a theme of an extension's) is any string.
        assert!(of("workbench.preferredDarkColorTheme").accepts(&json!("Solarized Dark")));
    }

    #[test]
    fn why_a_value_is_not_taken_is_said() {
        let said = |key: &str, v: serde_json::Value| find(key).expect(key).refuses(&v);
        assert_eq!(said("editor.tabSize", json!(4)), None);
        assert_eq!(said("editor.tabSize", json!("four")).as_deref(), Some("\"editor.tabSize\" takes a whole number."));
        assert_eq!(said("editor.tabSize", json!(64)).as_deref(), Some("\"editor.tabSize\" is from 1 to 32."));
        assert_eq!(said("editor.hover.delay", json!(-5)).as_deref(), Some("\"editor.hover.delay\" is from 0 to …."));
        assert_eq!(
            said("editor.minimap.side", json!("top")).as_deref(),
            Some("\"editor.minimap.side\" is one of \"left\", \"right\".")
        );
        assert_eq!(
            said("editor.minimap.enabled", json!("yes")).as_deref(),
            Some("\"editor.minimap.enabled\" takes true or false.")
        );
        assert_eq!(said("editor.rulers", json!(80)).as_deref(), Some("\"editor.rulers\" is a list of numbers."));
    }
