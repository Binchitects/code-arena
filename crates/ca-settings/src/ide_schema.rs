//! The IDE's own settings (the editor's, the workbench's, the Explorer's, source control's, the compare's, the
//! terminal's, the debugger's, the language servers'), declared as the others are in [`crate::schema`] and found by
//! [`crate::schema::find`] with them. A new one is a row added to [`ALL`].
//!
//! The rows here are the old Code Arena's (the 139 keys of its `settings-schema.ts`; `workbench.colorTheme` is in
//! [`crate::schema`] already), under VS Code's names, in its order and with its defaults: VS Code's, and where Code
//! Arena's own differ the description says so. A setting that may be set for one language (`"[python]": {…}`) is
//! [`Scope::Language`]; one that is the person's alone, [`Scope::User`]; the others may be a project's too.

use crate::schema::{Kind, Scope, Setting};

/// One of the IDE's settings: none is read from the environment.
const fn row(
    key: &'static str,
    kind: Kind,
    default: &'static str,
    scope: Scope,
    section: &'static str,
    description: &'static str,
) -> Setting {
    Setting { key, kind, default, description, scope, env: None, section }
}

